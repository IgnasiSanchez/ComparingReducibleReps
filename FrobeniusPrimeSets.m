/*
 * For each maximal cyclic subgroup up to G-conjugacy, return the element
 * class numbers of all its generators. classOf is ClassMap(G).
 */
function maximalCyclicGeneratorClasses(G, classOf)
    cyclicClasses := [];
    properClasses := {Integers() | };
    for entry in CyclicSubgroups(G) do
        H := entry`subgroup;
        d := Order(H);
        found := exists(h){g : g in H | Order(g) eq d};
        assert found;
        h := G!h;
        Append(~cyclicClasses, {classOf(h^a) : a in [1..d] | GCD(a,d) eq 1});

        // Every nonmaximal cyclic subgroup has prime index in some cyclic
        // overgroup. In H the unique subgroup of index r is generated by h^r.
        for r in PrimeDivisors(d) do
            Include(~properClasses, classOf(h^r));
        end for;
    end for;
    return [C : C in cyclicClasses | IsEmpty(C meet properClasses)];
end function;

/*
 * Compute the comparison prime lists for a finite Galois extension L/Q.
 * L                 Absolute number field (or Q).
 * S                 Rational primes excluded by the comparison problem.
 * n                 Dimension of the representations.
 * Candidates        Optional sequence or set of rational primes to search.
 *                   The default searches successive primes until coverage.
 *                   Both modes use increasing order and skip S and ramification.
 * EqualDeterminants Set true when the two determinants are known to agree.
 *
 * T takes the first eligible prime generating each maximal cyclic subgroup
 * up to conjugacy. For each such Frobenius g, Tprime represents the classes
 * of g^k for 1 <= k <= n (n-1 with equal determinants), once per nonidentity
 * class, at the first eligible prime. The identity itself has known trace n.
 * For the trivial group the identity suffices and both prime lists are empty.
 *
 * The optional third return value maps each selected prime to its Frobenius
 * element in the common permutation group. This certifies finite-group class
 * coverage; applying a trace comparison to Galois lifts uses the theorem's
 * hypotheses. An insufficient candidate list raises an error.
 */
function FrobeniusPrimeSets(L, S, n : Candidates := false, EqualDeterminants := false)
    error if Type(L) ne FldRat and not ISA(Type(L), FldNum),
        "L must be an absolute number field over Q.";
    error if Type(L) ne FldRat and not IsAbsoluteField(L),
        "FrobeniusPrimeSets requires an absolute extension over Q.";
    error if Type(n) ne RngIntElt or n lt 1, "n must be a positive integer.";
    error if Type(EqualDeterminants) ne BoolElt, "EqualDeterminants must be boolean.";
    error if Type(S) notin {SeqEnum, SetEnum} or
        not forall{p : p in S | Type(p) eq RngIntElt and IsPrime(p)},
        "S must be a sequence or set of rational primes.";
    excluded := {Integers() | p : p in S};

    restricted := not (Candidates cmpeq false);
    if restricted then
        error if Type(Candidates) notin {SeqEnum, SetEnum} or
            not forall{p : p in Candidates | Type(p) eq RngIntElt and IsPrime(p)},
            "Candidates must be a sequence or set of rational primes.";
        primes := Sort(SetToSequence({Integers() | p : p in Candidates}));
    end if;
    if Type(L) eq FldRat or Degree(L) eq 1 then
        return [Integers() | ], [Integers() | ], AssociativeArray();
    end if;

    // Use the permutation model chosen by FrobeniusElement, including when
    // Magma changes the defining polynomial for its Artin representations.
    G := Group(PermutationCharacter(L));
    error if Order(G) ne Degree(L), "L must be Galois over Q.";
    classOf := ClassMap(G);
    remaining := maximalCyclicGeneratorClasses(G, classOf);
    discriminant := Discriminant(Integers(L));
    powerBound := EqualDeterminants select n-1 else n;
    selected := [];
    required := {Integers() | };
    firstAt := AssociativeArray();
    p := 1;
    index := 0;
    while not IsEmpty(remaining) or not (required subset Keys(firstAt)) do
        if restricted then
            index +:= 1;
            error if index gt #primes, Sprintf(
                "Candidates exhausted: %o maximal cyclic subgroup classes and %o known power classes still missing.",
                #remaining, #(required diff Keys(firstAt)));
            p := primes[index];
        else
            p := NextPrime(p);
        end if;
        if p in excluded or discriminant mod p eq 0 then
            continue;
        end if;

        g := G!FrobeniusElement(L, p);
        c := classOf(g);
        if IsDefined(firstAt, c) then
            continue;
        end if;
        // A power class can occur before its generator's prime is selected.
        firstAt[c] := <p,g>;
        if exists(i){j : j in [1..#remaining] | c in remaining[j]} then
            Append(~selected, c);
            Remove(~remaining, i);
            for k in [1..Min(powerBound, Order(g)-1)] do
                Include(~required, classOf(g^k));
            end for;
        end if;
    end while;

    T := [Integers() | firstAt[c][1] : c in selected];
    Tprime := Sort([Integers() | firstAt[c][1] : c in required]);
    witnesses := AssociativeArray();
    for c in Seqset(selected) join required do
        prime, g := Explode(firstAt[c]);
        witnesses[prime] := g;
    end for;
    return T, Tprime, witnesses;
end function;
